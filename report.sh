#!/usr/bin/env bash
# ==============================================================================
# report.sh — Stage 4: Report generation
# ==============================================================================

report_menu() {
    ask_menu "Report output — what should we generate?" 2 \
        "Plain text only  (scan.txt, findings.txt, summary.txt)" \
        "Plain text + HTML report (recommended)" \
        "Plain text + HTML + keep raw nmap grepable output"
    REPORT_MODE="$MENU_CHOICE"
}

_severity_rank() {
    case "$1" in
        HIGH) echo 3 ;; MEDIUM) echo 2 ;; LOW) echo 1 ;; *) echo 0 ;;
    esac
}

generate_findings_file() {
    {
        printf 'FINDINGS — %s\n' "$TARGET"
        printf 'Generated: %s\n' "$(date '+%Y-%m-%d %H:%M:%S')"
        printf '%s\n\n' "======================================================================"

        if (( ${#FINDINGS[@]} == 0 )); then
            printf 'No findings were recorded for this target.\n'
        else
            local f severity title evidence recommendation n=1
            for f in "${FINDINGS[@]}"; do
                IFS='|' read -r severity title evidence recommendation <<< "$f"
                printf '[%d] SEVERITY: %s\n' "$n" "$severity"
                printf '    Title:          %s\n' "$title"
                printf '    Evidence:       %s\n' "$evidence"
                printf '    Recommendation: %s\n\n' "$recommendation"
                ((n++))
            done
        fi
    } > "$FINDINGS_FILE"
}

generate_summary_file() {
    local high=0 medium=0 low=0 info=0
    local f severity
    for f in "${FINDINGS[@]}"; do
        severity="${f%%|*}"
        case "$severity" in
            HIGH) ((high++)) ;; MEDIUM) ((medium++)) ;; LOW) ((low++)) ;; INFO) ((info++)) ;;
        esac
    done

    local risk="Low"
    (( medium > 0 )) && risk="Medium"
    (( high > 0 )) && risk="High"

    {
        printf 'SECURITY ASSESSMENT SUMMARY\n'
        printf '======================================================================\n'
        printf 'Target:        %s\n' "$TARGET"
        printf 'Resolved IP:   %s\n' "${TARGET_IP:-n/a}"
        printf 'Scan date:     %s\n' "$(date '+%Y-%m-%d %H:%M:%S')"
        printf 'Duration:      %s\n' "$(human_duration "$SCAN_DURATION")"
        printf '\nScan profile:\n'
        printf '  Firewall evasion:     %s\n' "$([[ "$FW_EVADE" == "1" ]] && echo "Yes (Xmas scan)" || echo "No")"
        printf '  Protocol:             %s\n' "${SCAN_PROTOCOL^^}"
        printf '  Operational profile:  %s\n' "$([[ "$STEALTH_PROFILE" == "redteam" ]] && echo "Red Team (maximum stealth)" || echo "Penetration Test (standard)")"
        printf '  Technique used:       %s\n' "$SCAN_TECHNIQUE_LABEL"
        printf '  Stealth measures:     %s\n' "$STEALTH_LABEL"
        printf '\nOpen ports (%d):\n' "${#OPEN_PORTS[@]}"
        if (( ${#OPEN_PORTS[@]} > 0 )); then
            for p in "${!OPEN_PORTS[@]}"; do
                printf '  - %-6s %-10s %s\n' "$p" "${OPEN_PORTS[$p]}" "${PORT_VERSION[$p]:-}"
            done | sort -n
        else
            printf '  (none detected)\n'
        fi
        printf '\nFindings by severity:\n'
        printf '  HIGH:   %d\n  MEDIUM: %d\n  LOW:    %d\n  INFO:   %d\n' "$high" "$medium" "$low" "$info"
        printf '\nOverall risk rating: %s\n' "$risk"
        printf '\nRisk explanation:\n'
        case "$risk" in
            High)   printf '  At least one HIGH severity, evidence-backed finding was confirmed.\n  These typically allow unauthorized access or information disclosure\n  and should be remediated before this host is exposed further.\n' ;;
            Medium) printf '  No HIGH severity findings, but MEDIUM findings indicate weaknesses\n  (e.g. outdated software, information disclosure) that reduce the\n  effort needed for further compromise and should be scheduled for fixes.\n' ;;
            *)      printf '  No HIGH/MEDIUM findings confirmed during this assessment. This does\n  not guarantee the host is fully secure — it reflects only the checks\n  this tool performed.\n' ;;
        esac
        printf '\nRecommendations:\n'
        if (( ${#FINDINGS[@]} == 0 )); then
            printf '  - Maintain current patching and configuration hygiene.\n  - Consider deeper manual testing beyond this tool'"'"'s automated checks.\n'
        else
            local f severity title _e recommendation
            for f in "${FINDINGS[@]}"; do
                IFS='|' read -r severity title _e recommendation <<< "$f"
                printf '  - [%s] %s: %s\n' "$severity" "$title" "$recommendation"
            done
        fi
        printf '\n----------------------------------------------------------------------\n'
        printf 'Generated by KarScan (karscan.sh) — Instant Software Solutions security track\n'
    } > "$SUMMARY_FILE"
}

generate_html_report() {
    local high=0 medium=0 low=0 info=0
    local f severity
    for f in "${FINDINGS[@]}"; do
        severity="${f%%|*}"
        case "$severity" in
            HIGH) ((high++)) ;; MEDIUM) ((medium++)) ;; LOW) ((low++)) ;; INFO) ((info++)) ;;
        esac
    done
    local risk="Low" risk_color="#2e7d32"
    (( medium > 0 )) && { risk="Medium"; risk_color="#e6a700"; }
    (( high > 0 )) && { risk="High"; risk_color="#c0392b"; }

    {
cat <<HTML_HEAD
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Security Assessment Report — ${TARGET}</title>
