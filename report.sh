  .evidence { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: 12.5px; background:#f2f3f5; padding:8px 10px; border-radius:6px; display:block; margin-top:4px; white-space:pre-wrap; word-break: break-word; }
