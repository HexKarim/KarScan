</header>

<div class="stat-row">
  <div class="stat"><div class="num">${#OPEN_PORTS[@]}</div>Open ports</div>
  <div class="stat"><div class="num" style="color:#c0392b">${high}</div>High</div>
  <div class="stat"><div class="num" style="color:#e6a700">${medium}</div>Medium</div>
  <div class="stat"><div class="num" style="color:#3468c0">${low}</div>Low</div>
  <div class="stat"><div class="num" style="color:#7a8390">${info}</div>Info</div>
</div>

<div class="card">
  <h2>Scan Profile</h2>
  <table>
    <tr><th>Firewall evasion</th><td>$([[ "$FW_EVADE" == "1" ]] && echo "Yes (Xmas scan)" || echo "No")</td></tr>
    <tr><th>Protocol</th><td>${SCAN_PROTOCOL^^}</td></tr>
    <tr><th>Operational profile</th><td>$([[ "$STEALTH_PROFILE" == "redteam" ]] && echo "Red Team (maximum stealth)" || echo "Penetration Test (standard)")</td></tr>
    <tr><th>Technique used</th><td>$(_html_escape "$SCAN_TECHNIQUE_LABEL")</td></tr>
    <tr><th>Stealth measures</th><td>$(_html_escape "$STEALTH_LABEL")</td></tr>
  </table>
</div>

<div class="card">
  <h2>Open Ports &amp; Services</h2>
  <table>
    <tr><th>Port</th><th>Service</th><th>Version / Banner</th></tr>
HTML_HEAD

        if (( ${#OPEN_PORTS[@]} > 0 )); then
            for p in "${!OPEN_PORTS[@]}"; do
                printf '<tr><td>%s</td><td>%s</td><td>%s</td></tr>\n' "$p" "${OPEN_PORTS[$p]}" "$(_html_escape "${PORT_VERSION[$p]:-}")"
            done | sort -n
        else
            printf '<tr><td colspan="3">No open ports detected</td></tr>\n'
        fi

cat <<'HTML_MID'
  </table>
</div>

<div class="card">
  <h2>Findings</h2>
HTML_MID

        if (( ${#FINDINGS[@]} == 0 )); then
            printf '<p>No findings were recorded for this target.</p>\n'
        else
            local n=1 title evidence recommendation
            for f in "${FINDINGS[@]}"; do
                IFS='|' read -r severity title evidence recommendation <<< "$f"
                cat <<FINDING_HTML
  <div style="padding:12px 0; border-top:1px solid #f0f0f0;">
    <span class="sev sev-${severity}">${severity}</span>
    <strong style="margin-left:8px;">$(_html_escape "$title")</strong>
    <span class="evidence">$(_html_escape "$evidence")</span>
    <div style="margin-top:6px; color:#4a525c; font-size:13.5px;"><strong>Recommendation:</strong> $(_html_escape "$recommendation")</div>
  </div>
FINDING_HTML
                ((n++))
            done
        fi

cat <<'HTML_TAIL'
</div>
<footer>Generated by KarScan (karscan.sh) — Instant Software Solutions security track</footer>
</div>
</body>
</html>
HTML_TAIL
    } > "$HTML_FILE"
}

_html_escape() {
    local s="$1"
    s="${s//&/&amp;}"; s="${s//</&lt;}"; s="${s//>/&gt;}"; s="${s//\"/&quot;}"
    printf '%s' "$s"
}

generate_reports() {
    section "Stage 4/4 — Report Generation"
    SCAN_DATE_HUMAN="$(date '+%Y-%m-%d %H:%M:%S')"

    generate_findings_file
    log_ok "Findings written to $FINDINGS_FILE"

    generate_summary_file
    log_ok "Summary written to $SUMMARY_FILE"

    log_ok "Raw scan log written to $SCAN_FILE"

    if [[ "$REPORT_MODE" != "1" ]]; then
        generate_html_report
        log_ok "HTML report written to $HTML_FILE"
    fi

    printf '\n'
    banner "Report ready: $REPORT_DIR"
}
